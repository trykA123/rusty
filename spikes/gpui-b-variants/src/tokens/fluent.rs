pub(super) fn theme(mode: Mode, segoe: Option<SharedString>) -> Theme {
    let ui = segoe.unwrap_or_else(|| "Google Sans Flex".into());
    Theme {
        mode,
        c: palette(mode),
        m: Metrics {
            text: px(13.5),
            small: px(12.5),
            tiny: px(11.5),
            row_h: px(30.),
            radius: px(4.),
            card_radius: px(8.),
            pane_gap: px(6.),
            tab_h: px(30.),
            path_h: px(30.),
            rail_w: px(244.),
            rail_item_h: px(34.),
            drawer_h: px(212.),
            fkey_h: px(40.),
            size_w: px(72.),
            date_w: px(104.),
            zebra: false,
            selection: Selection::Pill,
            active: ActiveMark::CardRing,
            kbd: KbdLook::Quiet,
            merged_path: false,
            caps_heads: false,
            cards: true,
        },
        f: Fonts {
            numbers: ui.clone(),
            ui,
            mono: "JetBrains Mono".into(),
        },
    }
}
