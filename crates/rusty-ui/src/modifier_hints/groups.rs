#[must_use]
pub fn place_of(command: &str) -> (usize, usize) {
    GROUPS
        .iter()
        .enumerate()
        .find_map(|(group, (_, commands))| {
            let at = commands.iter().position(|name| *name == command)?;
            Some((group, at))
        })
        .unwrap_or((ORDER.len() - 1, usize::MAX))
}
